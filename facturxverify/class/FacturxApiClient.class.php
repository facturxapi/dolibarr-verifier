/**
 * \file    facturxverify/class/FacturxApiClient.class.php
 * \ingroup facturxverify
 * \brief   Minimal HTTPS client for the FacturX API (validate, repair). No Dolibarr dependency.
 */

/**
 * Result of one API call. $data is the decoded JSON body, untouched.
 */
class FacturxApiResult
{
	/** @var int HTTP status, 0 when the request never got an answer */
	public $status = 0;
	/** @var array<string,mixed> Decoded JSON body */
	public $data = array();
	/** @var string Request id (X-Request-ID echoed or generated by the API) */
	public $requestId = '';
	/** @var string Transport or decoding error, empty when the API answered with JSON */
	public $transportError = '';

	/**
	 * @return bool True when the API answered 2xx with a JSON body
	 */
	public function ok()
	{
		return $this->transportError === '' && $this->status >= 200 && $this->status < 300;
	}

	/**
	 * Error code and message as served by the API (detail.error / detail.message, or flat).
	 *
	 * @return array{code:string,message:string}
	 */
	public function apiError()
	{
		$detail = isset($this->data['detail']) ? $this->data['detail'] : $this->data;
		if (is_string($detail)) {
			return array('code' => 'http_'.$this->status, 'message' => $detail);
		}
		$code = '';
		$message = '';
		if (is_array($detail)) {
			$code = isset($detail['error']) ? (string) $detail['error'] : (isset($detail['code']) ? (string) $detail['code'] : '');
			$message = isset($detail['message']) ? (string) $detail['message'] : '';
		}
		if ($code === '') {
			$code = 'http_'.$this->status;
		}
		return array('code' => $code, 'message' => $message);
	}
}

/**
 * FacturX API client.
 *
 * - HTTPS only (except an explicit http://127.0.0.1 / localhost base used by the test double);
 * - never follows a redirect, so the API key cannot leak to another host;
 * - one Idempotency-Key per operation; no automatic retry;
 * - identifies itself with User-Agent and X-FacturX-Client so the API can count calls coming from
 *   this connector (no personal data, no invoice data in these headers).
 */
class FacturxApiClient
{
	const CLIENT_NAME = 'dolibarr';

	/** @var string */
	private $baseUrl;
	/** @var string */
	private $apiKey;
	/** @var string */
	private $clientVersion;
	/** @var string */
	private $hostVersion;
	/** @var int */
	private $timeout;
	/** @var callable|null Test seam: function(string $method, string $url, array $headers, string $body): array{0:int,1:array,2:string} */
	private $transport;

	/**
	 * @param string        $baseUrl       e.g. https://api.facturxapi.com
	 * @param string        $apiKey        FacturX API key
	 * @param string        $clientVersion Version of this module
	 * @param string        $hostVersion   Version of Dolibarr
	 * @param int           $timeout       Seconds
	 * @param callable|null $transport     Replaces cURL in tests
	 */
	public function __construct($baseUrl, $apiKey, $clientVersion, $hostVersion = '', $timeout = 60, $transport = null)
	{
		$this->baseUrl = rtrim((string) $baseUrl, '/');
		$this->apiKey = (string) $apiKey;
		$this->clientVersion = (string) $clientVersion;
		$this->hostVersion = (string) $hostVersion;
		$this->timeout = (int) $timeout;
		$this->transport = $transport;
	}

	/**
	 * Is the base URL acceptable? https, or http on the loopback (local test double only).
	 *
	 * @param string $url URL
	 * @return bool
	 */
	public static function isAllowedBaseUrl($url)
	{
		$parts = parse_url((string) $url);
		if (!is_array($parts) || empty($parts['scheme']) || empty($parts['host'])) {
			return false;
		}
		if ($parts['scheme'] === 'https') {
			return true;
		}
		return $parts['scheme'] === 'http' && in_array($parts['host'], array('127.0.0.1', 'localhost'), true);
	}

	/**
	 * POST /api/v1/validate
	 *
	 * @param string $filename          File name sent to the API
	 * @param string $content           File content (PDF or XML)
	 * @param string $validationTarget  'france_2026' (EN 16931 + French rules) or 'en16931'
	 * @param string $lang              'fr' or 'en'
	 * @return FacturxApiResult
	 */
	public function validate($filename, $content, $validationTarget = 'france_2026', $lang = 'fr')
	{
		$query = http_build_query(array('validation_target' => $validationTarget, 'lang' => $lang));
		return $this->postFile('/api/v1/validate?'.$query, $filename, $content, array(), self::newUuid());
	}

	/**
	 * POST /api/v1/repair (standalone CII XML only). Amounts are never modified by the API.
	 *
	 * @param string $filename File name
	 * @param string $xml      CII XML
	 * @param string $lang     'fr' or 'en'
	 * @return FacturxApiResult
	 */
	public function repair($filename, $xml, $lang = 'fr')
	{
		$query = http_build_query(array('lang' => $lang));
		$constraints = json_encode(array('do_not_modify_amounts' => true));
		return $this->postFile('/api/v1/repair?'.$query, $filename, $xml, array('constraints' => $constraints), self::newUuid());
	}

	/**
	 * @return string User-Agent sent on every call
	 */
	public function userAgent()
	{
		$ua = 'facturx-dolibarr/'.$this->clientVersion;
		if ($this->hostVersion !== '') {
			$ua .= ' (Dolibarr '.$this->hostVersion.')';
		}
		return $ua;
	}

	/**
	 * @param string               $path           Path with query
	 * @param string               $filename       File name
	 * @param string               $content        Bytes
	 * @param array<string,string> $fields         Extra multipart fields
	 * @param string               $idempotencyKey Key
	 * @return FacturxApiResult
	 */
	private function postFile($path, $filename, $content, $fields, $idempotencyKey)
	{
		$result = new FacturxApiResult();
		if (!self::isAllowedBaseUrl($this->baseUrl)) {
			$result->transportError = 'base_url_not_https';
			return $result;
		}
		if ($this->apiKey === '') {
			$result->transportError = 'missing_api_key';
			return $result;
		}
		$boundary = 'facturx-dolibarr-'.substr(hash('sha256', $idempotencyKey), 0, 32);
		$body = self::multipart($boundary, $fields, $filename, $content);
		$headers = array(
			'Accept: application/json',
			'Content-Type: multipart/form-data; boundary='.$boundary,
			'X-API-Key: '.$this->apiKey,
			'Idempotency-Key: '.$idempotencyKey,
			'User-Agent: '.$this->userAgent(),
			'X-FacturX-Client: '.self::CLIENT_NAME.'/'.$this->clientVersion,
		);
		list($status, $responseHeaders, $raw, $error) = $this->send('POST', $this->baseUrl.$path, $headers, $body);
		$result->status = $status;
		if ($error !== '') {
			$result->transportError = $error;
			return $result;
		}
		$decoded = json_decode((string) $raw, true);
		if (!is_array($decoded)) {
			$result->transportError = 'non_json_response';
			$result->data = array('detail' => array('message' => substr((string) $raw, 0, 300)));
			return $result;
		}
		$result->data = $decoded;
		$result->requestId = isset($decoded['request_id']) ? (string) $decoded['request_id'] : (isset($responseHeaders['x-request-id']) ? (string) $responseHeaders['x-request-id'] : '');
		return $result;
	}

	/**
	 * @param string   $method  Method
	 * @param string   $url     URL
	 * @param string[] $headers Headers
	 * @param string   $body    Body
	 * @return array{0:int,1:array<string,string>,2:string,3:string}
	 */
	private function send($method, $url, $headers, $body)
	{
		if ($this->transport !== null) {
			$r = call_user_func($this->transport, $method, $url, $headers, $body);
			return array((int) $r[0], (array) $r[1], (string) $r[2], isset($r[3]) ? (string) $r[3] : '');
		}
		if (!function_exists('curl_init')) {
			return array(0, array(), '', 'curl_missing');
		}
		$responseHeaders = array();
		$ch = curl_init($url);
		curl_setopt_array($ch, array(
			CURLOPT_CUSTOMREQUEST => $method,
			CURLOPT_POSTFIELDS => $body,
			CURLOPT_HTTPHEADER => $headers,
			CURLOPT_RETURNTRANSFER => true,
			CURLOPT_FOLLOWLOCATION => false,
			CURLOPT_TIMEOUT => $this->timeout,
			CURLOPT_CONNECTTIMEOUT => 15,
			CURLOPT_PROTOCOLS => CURLPROTO_HTTPS | CURLPROTO_HTTP,
			CURLOPT_HEADERFUNCTION => function ($ch, $line) use (&$responseHeaders) {
				$pos = strpos($line, ':');
				if ($pos !== false) {
					$responseHeaders[strtolower(trim(substr($line, 0, $pos)))] = trim(substr($line, $pos + 1));
				}
				return strlen($line);
			},
		));
		$raw = curl_exec($ch);
		$status = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
		$error = $raw === false ? 'transport: '.curl_error($ch) : '';
		curl_close($ch);
		return array($status, $responseHeaders, $raw === false ? '' : (string) $raw, $error);
	}

	/**
	 * @param string               $boundary Boundary
	 * @param array<string,string> $fields   Fields
	 * @param string               $filename File name
	 * @param string               $content  File bytes
	 * @return string
	 */
	public static function multipart($boundary, $fields, $filename, $content)
	{
		$eol = "\r\n";
		$out = '';
		foreach ($fields as $name => $value) {
			$out .= '--'.$boundary.$eol.'Content-Disposition: form-data; name="'.$name.'"'.$eol.$eol.$value.$eol;
		}
		$mime = strncmp($content, '%PDF-', 5) === 0 ? 'application/pdf' : 'application/xml';
		$safe = str_replace(array('"', "\r", "\n"), '_', $filename);
		$out .= '--'.$boundary.$eol.'Content-Disposition: form-data; name="file"; filename="'.$safe.'"'.$eol;
		$out .= 'Content-Type: '.$mime.$eol.$eol.$content.$eol;
		$out .= '--'.$boundary.'--'.$eol;
		return $out;
	}

	/**
	 * @return string RFC 4122 v4 UUID
	 */
	public static function newUuid()
	{
		$b = random_bytes(16);
		$b[6] = chr((ord($b[6]) & 0x0f) | 0x40);
		$b[8] = chr((ord($b[8]) & 0x3f) | 0x80);
		$h = bin2hex($b);
		return substr($h, 0, 8).'-'.substr($h, 8, 4).'-'.substr($h, 12, 4).'-'.substr($h, 16, 4).'-'.substr($h, 20, 12);
	}
}
